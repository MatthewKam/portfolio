/**
 * Run with `npm run data:datacenters`. Saves the snapshot the page falls back on
 * and geocodes any new site, since neither Epoch's address field nor the page can.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { buildDataset, parseCsv, stateOf, STATES } from '../api/_epoch.js';
import { COORDS } from '../api/_coords.js';

// Where the address field can't be geocoded. Town-level pins where the address names a
// town, and just the state where only the site's name gives it: no pin is guessed.
const MANUAL = {
	'Amazon Madison Mega Site': { lat: 32.61, lon: -90.04, state: 'MS', approx: true },
	'Google Papillion': { lat: 41.154, lon: -96.042, state: 'NE', approx: true },
	'AWS New Albany': { lat: 40.081, lon: -82.809, state: 'OH', approx: true }, // The address has no town; the name does.
	'Meta Eagle Mountain': { lat: 40.333, lon: -112.081, state: 'UT', approx: true },
	'Google Mesa': { state: 'AZ' },
	'Google Kansas City East': { state: 'MO' },
	'Google Storey County': { state: 'NV' },
	'OpenAI Stargate Michigan': { state: 'MI' },
	'OpenAI Stargate Milam': { state: 'TX' },
	'OpenAI Stargate New Mexico': { state: 'NM' },
	'OpenAI Stargate Wisconsin': { state: 'WI' },
};
const coords = { ...COORDS, ...MANUAL };
const round = (n) => Math.round(n * 1000) / 1000;

async function census(address) {
	const q = new URLSearchParams({ address, benchmark: 'Public_AR_Current', format: 'json' });
	const res = await fetch(`https://geocoding.geo.census.gov/geocoder/locations/onelineaddress?${q}`);
	const hit = (await res.json()).result?.addressMatches?.[0];
	return hit && { lat: round(hit.coordinates.y), lon: round(hit.coordinates.x), state: hit.addressComponents.state };
}

// Rural sites often aren't in the census address list, but their ZIP code or town is on the map.
async function place(address) {
	// Only a number after a state or at the very end: street numbers are often five digits too.
	const zip = address.match(/\b[A-Z]{2}\s+(\d{5})\b/)?.[1] ?? address.match(/\b(\d{5})\s*(?:, USA)?$/)?.[1];
	const town = address.split(',').at(-2)?.trim();
	for (const name of [zip, town]) {
		if (!name) continue;
		const res = await fetch(`https://geocoding-api.open-meteo.com/v1/search?count=10&countryCode=US&name=${encodeURIComponent(name)}`);
		const state = stateOf(address);
		const wanted = Object.keys(STATES).find((k) => STATES[k] === state);
		// Town names repeat: Eagle Mountain is in Utah and Minnesota, so never accept the wrong state.
		const hit = (await res.json()).results?.find((r) => !wanted || r.admin1 === wanted);
		if (hit) return { lat: round(hit.latitude), lon: round(hit.longitude), state, approx: true };
	}
	return null;
}

const centers = parseCsv(await (await fetch('https://epoch.ai/data/data_centers/data_centers.csv')).text());
for (const c of centers) {
	if (c.Country !== 'United States' || !c.Address.trim() || coords[c.Name]) continue;
	const found = (await census(c.Address).catch(() => null)) ?? (await place(c.Address).catch(() => null));
	if (found) coords[c.Name] = found;
	else console.warn(`No location for ${c.Name}: ${c.Address}`);
}

const sorted = Object.fromEntries(Object.entries(coords).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(new URL('../api/_coords.js', import.meta.url), `// Generated by scripts/update-datacenters.mjs.\nexport const COORDS = ${JSON.stringify(sorted, null, '\t')};\n`);
const data = await buildDataset(sorted);
await writeFile(new URL('../public/data/ai-datacenters.json', import.meta.url), JSON.stringify(data));
const mapped = data.sites.filter((s) => s.lat !== null).length;
console.log(`${data.sites.length} US sites, ${mapped} on the map`);
